"""원티드 WAF 차단 응답 처리.

실제로 받은 응답이 이것이었다:

    403 ERROR
    The request could not be satisfied.
    Request blocked.
    Generated by cloudfront (CloudFront)

AWS 공식 문서는 CloudFront 의 'Request blocked' 를 WAF 규칙이 요청을 의도적으로
차단한 경우로 못 박는다 — 오리진 장애나 설정 누락이 아니다. 즉 '원티드가 설정을
안 해둔 것' 이 아니라 '원티드가 설정해 둔 규칙에 막힌 것' 이다.

그래서 이 테스트가 보는 것은 두 가지다.
  1) 차단을 일시적 오류로 흘리지 않고 차단으로 보고하는가
  2) 차단을 만났을 때 더 세게 시도하지 않고 멈추는가
"""
import httpx
import pytest

from jobcal.sources import wanted as wanted_module
from jobcal.sources.wanted import LIST_ENDPOINT, WantedSource

CLOUDFRONT_BODY = """<!DOCTYPE HTML><html><head><title>ERROR: The request could not be satisfied</title></head>
<body><h1>403 ERROR</h1><h2>The request could not be satisfied.</h2>
<p>Request blocked. We can't connect to the server for this app or website at this time.</p>
<hr><pre>Generated by cloudfront (CloudFront)</pre></body></html>"""


class StubClient:
    """httpx.Client 대역 — 호출 횟수를 센다."""

    def __init__(self, response: httpx.Response):
        self.response = response
        self.calls = 0

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False

    def get(self, url, params=None):
        self.calls += 1
        return self.response


def cloudfront_403() -> httpx.Response:
    return httpx.Response(
        status_code=403,
        headers={"server": "CloudFront", "via": "1.1 abc123.cloudfront.net (CloudFront)"},
        text=CLOUDFRONT_BODY,
        request=httpx.Request("GET", LIST_ENDPOINT),
    )


@pytest.fixture
def stub(monkeypatch):
    client = StubClient(cloudfront_403())
    monkeypatch.setattr(wanted_module.httpx, "Client", lambda **kw: client)
    return client


def source() -> WantedSource:
    # robots 확인은 별도 경로라 여기서는 끈다 — 보려는 것은 차단 응답 처리다.
    return WantedSource(
        acknowledged_robots=True, check_robots_at_runtime=False, delay=0.0, max_pages=10
    )


def test_waf_block_is_reported_as_a_block(stub):
    result = source().fetch(["토스랩"])
    assert result.complete is False
    message = " ".join(result.errors)
    assert "자동 접근이 차단" in message


def test_message_names_the_actual_blocker(stub):
    """'403 Forbidden' 만 찍으면 다음 사람이 재시도를 떠올린다 — 누가 막았는지 적는다."""
    result = source().fetch(["토스랩"])
    message = " ".join(result.errors)
    assert "CloudFront" in message and "WAF" in message


def test_block_does_not_trigger_retries_or_escalation(stub):
    """차단을 만나면 페이지를 더 넘기지 않고 즉시 멈춘다.

    max_pages=10 인데 요청이 1회만 나가야 한다. 차단된 엔드포인트를 열 번 더
    두드리는 것은 부담 축에서도 나쁘고 차단을 굳히기만 한다.
    """
    source().fetch(["토스랩"])
    assert stub.calls == 1


def test_blocked_source_never_deletes_calendar_events(stub):
    """차단된 소스는 전수가 아니므로 마감 판정에 쓰이지 않는다.

    이게 빠지면 WAF 에 막힌 날 캘린더의 원티드 일정이 전부 지워진다.
    """
    from jobcal.calendar_sync import ExistingEvent, build_plan

    result = source().fetch(["토스랩"])
    existing = [ExistingEvent("jobcal" + "a" * 40, "wanted", "hash")]
    complete = {result.source} if result.complete else set()

    plan = build_plan([], existing, complete_sources=complete)
    assert plan.delete == []
    assert len(plan.delete_skipped) == 1


def test_robots_check_failure_also_stops(monkeypatch):
    """robots.txt 를 못 읽은 것은 '허용' 이 아니다 — 무인 실행에서는 멈춘다."""
    monkeypatch.setattr(
        wanted_module,
        "check_robots",
        lambda url, user_agent="*": {
            "allowed": True, "crawl_delay": None,
            "robots_url": "https://www.wanted.co.kr/robots.txt",
            "error": "robots.txt 를 가져오지 못했습니다: 403 Forbidden",
        },
    )
    result = WantedSource(acknowledged_robots=True, delay=0.0).fetch(["토스랩"])
    assert result.complete is False
    assert any("robots.txt 확인 실패" in e for e in result.errors)


def test_disabled_by_default_never_sends_a_request(monkeypatch):
    sent = []
    monkeypatch.setattr(
        wanted_module.httpx, "Client", lambda **kw: sent.append(1) or StubClient(cloudfront_403())
    )
    result = WantedSource().fetch(["토스랩"])
    assert result.complete is False
    assert sent == []
